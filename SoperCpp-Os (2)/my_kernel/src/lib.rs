pub const PIC_1_OFFSET: u8 = 32;
pub const PIC_2_OFFSET: u8 = PIC_1_OFFSET + 8;

pub static PICS: Mutex<ChainedPics> =
    Mutex::new(unsafe { ChainedPics::new(PIC_1_OFFSET, PIC_2_OFFSET) });

#[derive(Debug, Clone, Copy)]
#[repr(u8)]
pub enum InterruptIndex {
    Timer = PIC_1_OFFSET,       
    Keyboard = PIC_1_OFFSET + 1, 
}

lazy_static! {
    static ref IDT: InterruptDescriptorTable = {
        let mut idt = InterruptDescriptorTable::new();
        idt[InterruptIndex::Keyboard as u8].set_handler_fn(keyboard_interrupt_handler);
        idt[InterruptIndex::Timer as u8].set_handler_fn(timer_interrupt_handler);
        idt.double_fault.set_handler_fn(double_fault_handler);
        idt
    };
}

pub fn init_idt() {
    IDT.load();
}

extern "x86-interrupt" fn timer_interrupt_handler(_stack_frame: InterruptStackFrame) {
    unsafe {
        PICS.lock().notify_end_of_interrupt(InterruptIndex::Timer as u8);
    }
}

lazy_static! {
    static ref KEYBOARD: Mutex<Keyboard<layouts::Us104Key, ScancodeSet1>> =
        Mutex::new(Keyboard::new(ScancodeSet1::new(), layouts::Us104Key, HandleControl::Ignore));
}

// مقاطعة الكيبورد المستقلة والآمنة
extern "x86-interrupt" fn keyboard_interrupt_handler(_stack_frame: InterruptStackFrame) {
    let mut port: Port<u8> = Port::new(0x60);
    let scancode: u8 = unsafe { port.read() };

    let mut keyboard = KEYBOARD.lock();
    if let Ok(Some(key_event)) = keyboard.add_byte(scancode) {
        if let Some(decoded_key) = keyboard.process_keyevent(key_event) {
            let mut term = TERMINAL.lock();
            term.handle_key(decoded_key);
        }
    }

    unsafe {
        PICS.lock().notify_end_of_interrupt(InterruptIndex::Keyboard as u8);
    }
}

extern "x86-interrupt" fn double_fault_handler(
    _stack_frame: InterruptStackFrame,
    _error_code: u64,
) -> ! {
    panic!("EXCEPTION: DOUBLE FAULT\n");
}

#[panic_handler]
fn panic(_info: &PanicInfo) -> ! {
    let mut writer = WRITER.lock();
    writer.clear_screen(0x00FF0000); 
    loop {
        x86_64::instructions::hlt();
    }
}

// --- نقطة البداية للنواة ---
#[no_mangle]
pub extern "C" fn _start(boot_info_addr: u64) -> ! {
    init_idt();
    
    unsafe { 
        let mut pics = PICS.lock();
        pics.initialize();
        // إغلاق المقاطعات غير الضرورية والاعتماد على الماستر فقط (الكيبورد والتايمر)
        pics.write_masks(0b11111100, 0b11111111);
    }
    
    x86_64::instructions::interrupts::enable();

    // 1. تهيئة الشاشة ورسم سطح المكتب وشريط المهام أولاً
    {
        let mut writer = WRITER.lock();
        *writer = FramebufferWriter::init_from_multiboot(boot_info_addr);
        
        gui::DesktopGUI::draw_desktop(&mut writer);
        
        writer.column_position = 3;
        writer.row_position = 2;
        writer.write_string("SoperCpp-Os 720p Graphical Mode Initialized Successfully.\n");
    }

    // 2. تهيئة وتشغيل التيرمنال
    {
        let mut term = TERMINAL.lock();
        term.init();
    }

    loop {
        x86_64::instructions::hlt();
    }
}