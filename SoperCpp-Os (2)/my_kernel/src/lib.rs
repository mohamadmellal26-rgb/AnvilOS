pub struct FramebufferWriter {
    pub framebuffer: *mut u32,
    pub width: usize,
    pub height: usize,
    pub pitch: usize,
    pub column_position: usize,
    pub row_position: usize,
}

unsafe impl Send for FramebufferWriter {}
unsafe impl Sync for FramebufferWriter {}

impl FramebufferWriter {
    pub fn init_from_multiboot(_addr: u64) -> Self {
        FramebufferWriter {
            framebuffer: 0xfd000000 as *mut u32,
            width: 1280,
            height: 720,
            pitch: 1280,
            column_position: 0,
            row_position: 0,
        }
    }

    pub fn draw_pixel(&mut self, x: usize, y: usize, color: u32) {
        if x < self.width && y < self.height {
            unsafe {
                let pixel_offset = y * self.pitch + x;
                core::ptr::write_volatile(self.framebuffer.add(pixel_offset), color);
            }
        }
    }

    pub fn clear_screen(&mut self, color: u32) {
        for y in 0..self.height {
            for x in 0..self.width {
                self.draw_pixel(x, y, color);
            }
        }
        self.column_position = 0;
        self.row_position = 0;
    }

    pub fn write_string(&mut self, s: &str) {
        for byte in s.bytes() {
            self.write_byte(byte);
        }
    }

    pub fn backspace(&mut self) {
        if self.column_position > 0 {
            self.column_position -= 1;
        } else if self.row_position > 0 {
            self.row_position -= 1;
            self.column_position = BUFFER_WIDTH - 1;
        }

        let start_x = 30 + (self.column_position * 9);
        let start_y = 30 + (self.row_position * 18);

        for row in 0..16 {
            for col in 0..8 {
                self.draw_pixel(start_x + col, start_y + row, 0x00000000);
            }
        }
    }

    pub fn write_byte(&mut self, byte: u8) {
        match byte {
            b'\n' => {
                self.new_line();
            }
            b'\x08' => {
                self.backspace();
            }
            _b => {
                if self.column_position >= BUFFER_WIDTH {
                    self.new_line();
                }
                
                let start_x = 30 + (self.column_position * 9);
                let start_y = 30 + (self.row_position * 18);
                
                let char_index = if byte >= 32 && (byte as usize) < 32 + FONT_8X16.len() {
                    (byte - 32) as usize
                } else {
                    0 
                };
                
                let glyph = &FONT_8X16[char_index];

                for (row, &row_byte) in glyph.iter().enumerate() {
                    for col in 0..8 {
                        let is_pixel = (row_byte & (1 << (7 - col))) != 0;
                        let color = if is_pixel {
                            0x00FFFFFF 
                        } else {
                            0x00000000 
                        };
                        self.draw_pixel(start_x + col, start_y + row, color);
                    }
                }

                self.column_position += 1;
            }
        }
    }

    pub fn new_line(&mut self) {
        self.column_position = 0;
        self.row_position += 1;
        if self.row_position >= BUFFER_HEIGHT {
            self.row_position = 0;
        }
    }
}

